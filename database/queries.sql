-- Demonstration queries for the DBMS component

-- 1. JOIN via view: applications with applicant and program
SELECT * FROM v_application_detail ORDER BY priority;

-- 2. Aggregation via view: admission statistics per program
SELECT * FROM v_admission_stats;

-- 3. Eligibility check (join with rules)
SELECT u.full_name, p.program_name,
       (s.twelfth_pct >= r.min_twelfth_pct
        AND s.tenth_pct >= r.min_tenth_pct
        AND s.entrance_score >= r.min_entrance) AS eligible
FROM applications a
JOIN students s          ON s.student_id = a.student_id
JOIN users u             ON u.user_id = s.user_id
JOIN programs p          ON p.program_id = a.program_id
JOIN eligibility_rules r ON r.program_id = a.program_id;

-- 4. Subquery: programs with above-average application counts
SELECT program_id, COUNT(*) AS c
FROM applications GROUP BY program_id
HAVING COUNT(*) > (SELECT AVG(cnt) FROM (SELECT COUNT(*) cnt FROM applications GROUP BY program_id) t);

-- 5. Status history (filled by trigger)
SELECT * FROM application_status_history ORDER BY changed_at;

-- 6. Notifications generated by trigger
SELECT * FROM notifications ORDER BY created_at DESC;

-- =====================================================================
-- STUDENT ERP DEMONSTRATION QUERIES (read-only)
-- =====================================================================

-- 7. Attendance by enrolled student and course, including courses with no marks yet
SELECT enrollment_no, full_name, course_code, course_name, semester,
       classes, attended, attendance_pct
FROM v_student_attendance_detail
ORDER BY enrollment_no, semester, course_code;

-- 8. Course results, weighted SGPA/CGPA source data and grade points
SELECT u.full_name, s.enrollment_no, a.course_code, a.semester,
       a.marks_earned, a.marks_available, a.percentage, a.grade_point, a.credits
FROM v_student_academic_summary a
JOIN students s ON s.student_id = a.student_id
JOIN users u ON u.user_id = s.user_id
ORDER BY s.enrollment_no, a.semester, a.course_code;

-- 9. Fee schedule, paid amount and outstanding amount for each application
SELECT u.full_name, s.enrollment_no, f.program_name, f.fee_type,
       f.fee_amount, f.paid_amount, f.outstanding_amount
FROM v_student_fee_summary f
JOIN students s ON s.student_id = f.student_id
JOIN users u ON u.user_id = s.user_id
ORDER BY s.enrollment_no, f.application_id, f.fee_type;

-- 10. Aggregate students with attendance shortage (HAVING)
SELECT enrollment_no, full_name,
       ROUND(AVG(attendance_pct), 1) AS average_course_attendance,
       COUNT(*) AS course_count
FROM v_student_attendance_detail
WHERE classes > 0
GROUP BY enrollment_no, full_name
HAVING AVG(attendance_pct) < 75
ORDER BY average_course_attendance;

-- 11. Applications with a successful payment above the average transaction amount (subquery)
SELECT a.application_id, u.full_name, SUM(pay.amount) AS successful_payments
FROM applications a
JOIN students s ON s.student_id = a.student_id
JOIN users u ON u.user_id = s.user_id
JOIN payments pay ON pay.application_id = a.application_id AND pay.status = 'SUCCESS'
GROUP BY a.application_id, u.full_name
HAVING SUM(pay.amount) > (SELECT AVG(amount) FROM payments WHERE status = 'SUCCESS')
ORDER BY successful_payments DESC;

-- 12. Recent attendance, result and examination audit events
SELECT entity_type, entity_id, action, actor_user_id, old_data, new_data, recorded_at
FROM erp_audit_log
ORDER BY recorded_at DESC
LIMIT 25;

